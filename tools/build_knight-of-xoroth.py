def stance_alert(spec_name, label, auras, gate_id, art, bands, extra=()):
    """A missing-stance alert: fires when NONE of `auras` is up AND the spec's
    stance spell is known -- so a levelling character who cannot take a stance
    yet is not nagged. The Stormbringer NO AEGIS shape."""
    band = f"KX {spec_name} Alerts"
    keys = [str(i) for _n, i in auras] + [n for n, _i in auras]
    d = B.icon(
        f"{band} {label.title()}", band,
        [B.aura_trigger(keys, own_only=False, show_on="showOnMissing"),
         B.spell_known_trigger(gate_id, exact=False)],
        ic(art), size=SZ_ALERT, desaturate=True,
        subregions=[B.sub_background(),
                    B.sub_text(label, size=10, anchor="INNER_BOTTOM",
                               color=(1, 0.35, 0.35, 1)),
                    B.sub_border(color=(1, 0.2, 0.2, 1), size=2, offset=1,
                                 edge=EDGE),
                    B.sub_glow(True, "buttonOverlay", (1, 0.3, 0.3, 1))])
    NEEDS_ALL.add(d["id"])       # missing-aura AND spell-known, never "any"
    out = [add(d)] + list(extra)
    add(B.dynamicgroup(band, f"KX {spec_name}", out, x=0, y=Y_ALERT,
                       grow="HORIZONTAL", space=6))
    bands.append(band)


