"""Build the `Knight of Xoroth [CoA]` WeakAura pack for Ascension Conquest of Azeroth.

Written as CONTENT over the shared engine -- the build_chronomancer.py shape,
no convergence flags. Layout follows notes/layout-standard.md.

        [ alerts: NO PESTILENCE / NO PET / NO OATH ]  <- per spec, active-only
        [ on TARGET: your DoTs / debuffs ]            <- band 2, active-only
        [ on me: procs, running CDs, buffs ]          <- band 3, active-only
              [  MAIN ROW - flush         ]           <- band 4
              [  resource envelope        ]           <- band 5, fixed height
              [ offensive cooldowns       ]           <- band 6, wraps at 9
              [ defensive + utility       ]           <- band 7, wraps at 9
              [ long-term buffs           ]           <- band 8, active-only

Class shape (notes/requirements-knight-of-xoroth.md):

  * THE DEMONFIRE ECONOMY. Every spec builds Demonfire (aura 500906,
    "Consumed to empower abilities. Stacks 6 times") with its fillers and
    dumps it into scaling spenders. The envelope renders a 6-cell stack_bar,
    the rage bar under it, and Demon's Blood (800999, stacks to 10 -- the
    Black Shield / Juggernaut fuel) as a thin minor bar -- three bands in the
    fixed envelope, the Stormbringer-maelstrom heights. Identical on every
    spec, so no height variance.

  * TRANSFORM MAIN ROWS. Three talents replace a button outright ("Transforms
    your X into Y" -- Sidekick talent text, quoted in requirements sec2):
    Sever -> Brimstone Bludgeon and Flames of Xoroth -> Warbringer on war,
    Infernal Strike -> Shieldgore on defiance. This fork resolves no spell
    overrides, so each spec's main row tracks the REPLACEMENT's own id
    directly -- the Stormbringer Tempest Sovereign precedent, with the
    build-defining assumption declared in the requirements doc. The two
    choose-one defiance nodes (Hellfire Bellows; Impcaller, which removes
    Call: Hellfire Imp) get a native ["Spell Known"] gate trigger instead, so
    an untalented character sees no dead button.

  * THE PET SPEC IS HELLFIRE. A permanent Greater Imp (Summon: Greater Imp
    520661, granted by the tree node 92101). NO PET alert asks the PET unit
    for Greater Imp Scaling (520662) and gates on knowing the summon -- the
    Stormbringer/Tinker shape. Doom (802602) is a player button transforming
    the pet into a Doomguard; its window rides the buff row with unit="pet".
    Defiance's Hellfire Imps are 30s cooldown-length summons regenerated by
    the rotation -- no alert, no count (requirements sec6.4). The Imp's OWN
    spellbook (Burst, Burning Slap, Burning Mischief, the Lesser Pestilences)
    is `ignore` per the Chronobuff precedent.

  * PESTILENCES ARE STANCES. War and hellfire each keep one emanating
    (Sidekick: "Keep Pestilence of Death active before every pull" / "Keep
    Pestilence of Apocalypse up almost constantly"), so each gets a
    NO PESTILENCE alert firing when none of the five stance auras is up.
    Defiance's analog is Oath of Defiance (804285), the tank stance -> the
    NO OATH alert. All three alerts gate on knowing the spec's stance.

  * DEFIANCE TANKS (spec-roles.md, Sidekick-sourced). Nothing structural
    changes: its main row is the cited tanking loop, Snarl (the taunt) rides
    the utility row -- the felsworn-tyrant precedent.

WA_GLOW=1 additionally glows main-row icons the moment they come off cooldown.
"""
