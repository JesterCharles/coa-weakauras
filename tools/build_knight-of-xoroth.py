def envelope(spec_name, bands):
    """Demonfire + rage + Demon's Blood. Identical on all three specs, three
    bands in the fixed-height envelope (~-156..-186) -- the Stormbringer
    maelstrom heights, so every anchor below is unchanged.

    Demonfire sits NEAREST the main row because the spend decision is the
    thing the rotation is played around (every spec's Resource paragraph);
    rage underneath; Demon's Blood is the thin minor meter -- background AND
    independent (it feeds Black Shield / Juggernaut when SPENT), so `minor`
    rather than `fused`.
    """
    w = row_w(5)
    W.stack_bar(f"KX {spec_name} Demonfire", f"KX {spec_name}", DEMONFIRE,
                DEMONFIRE_CELLS, (1.00, 0.55, 0.20), -160,
                B.health_trigger("player"), w, bands, h=10)
    bands.append(rage_bar(f"KX {spec_name} Rage", f"KX {spec_name}", -171, w))
    W.stack_bar(f"KX {spec_name} Blood", f"KX {spec_name}", DEMONS_BLOOD,
                BLOOD_CELLS, (0.75, 0.20, 0.25), -182,
                B.health_trigger("player"), w, bands, h=8)


def rage_bar(gid, parent, y, w):
    """Rage is power type 1 on a 3.3.5 client. mana_bar hardcodes 0, so this
    is the same aurabar with the right powertype -- the one class-content
    divergence the resource envelope needs."""
    add(B.aurabar(gid, parent, [B.power_trigger("player", 1)],
                  x=0, y=y, w=w, h=10,
                  color=(0.85, 0.25, 0.25, 1.0),
                  subregions=[
                      B.sub_text("%p", size=9, anchor="INNER_RIGHT", x=-4,
                                 justify="RIGHT"),
                  ]))
    return gid


def known_gate(d, spell_id):
    """AND a native ["Spell Known"] trigger onto a display, so it only renders
    while `spell_id` is known.

    For the choose-one defiance talents: Hellfire Bellows exists only when its
    node is taken, and Impcaller REMOVES Call: Hellfire Imp (a 3.3.5 server
    changes a button by granting the new spell and taking the base away, and
    this fork resolves no overrides). The load-side spec gate cannot express
    this -- load.spellknown holds ONE id and assert_gated requires the spec
    signature on single-spec leaves -- so the gate rides the trigger list,
    with NEEDS_ALL keeping `disjunctive` at "all".

    Only legal on a display with no PROC_GLOW triggers: under "all" a proc
    trigger would become a second gate and hide the button until it procs.
    """
    trs = triggers_of(d)
    assert len(trs) == 1, f"known_gate on {d['id']}: expected 1 trigger"
    trs.append(B.spell_known_trigger(spell_id))
    d["triggers"] = B._trigger_wrap(trs)
    d["triggers"].pop("disjunctive", None)
    NEEDS_ALL.add(d["id"])
    return d


